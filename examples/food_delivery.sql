-- Sample database for QueryPilot's "Use your own database" feature: a food delivery app.
-- Upload it from the database chip (top right of the chat) > Change.
-- Try: "Which city has the highest average order value?", "Top 5 restaurants by revenue",
--      "Only vegetarian ones", "Which delivery partner has the best average rating?",
--      "How many orders were cancelled each month in 2026?"

CREATE TABLE Cities (
    CityID    INTEGER PRIMARY KEY,
    CityName  TEXT NOT NULL,
    State     TEXT NOT NULL
);

CREATE TABLE Restaurants (
    RestaurantID  INTEGER PRIMARY KEY,
    Name          TEXT NOT NULL,
    Cuisine       TEXT NOT NULL,
    CityID        INTEGER NOT NULL REFERENCES Cities(CityID),
    IsVegetarian  INTEGER NOT NULL DEFAULT 0,   -- 1 = pure veg
    OpenedOn      TEXT NOT NULL                 -- 'YYYY-MM-DD'
);

CREATE TABLE MenuItems (
    ItemID        INTEGER PRIMARY KEY,
    RestaurantID  INTEGER NOT NULL REFERENCES Restaurants(RestaurantID),
    ItemName      TEXT NOT NULL,
    Price         REAL NOT NULL                 -- rupees
);

CREATE TABLE Users (
    UserID      INTEGER PRIMARY KEY,
    FullName    TEXT NOT NULL,
    CityID      INTEGER NOT NULL REFERENCES Cities(CityID),
    JoinedOn    TEXT NOT NULL,
    IsPremium   INTEGER NOT NULL DEFAULT 0      -- 1 = paid membership
);

CREATE TABLE DeliveryPartners (
    PartnerID   INTEGER PRIMARY KEY,
    FullName    TEXT NOT NULL,
    CityID      INTEGER NOT NULL REFERENCES Cities(CityID),
    Vehicle     TEXT NOT NULL                   -- 'Bike', 'Scooter', 'Bicycle'
);

CREATE TABLE Orders (
    OrderID        INTEGER PRIMARY KEY,
    UserID         INTEGER NOT NULL REFERENCES Users(UserID),
    RestaurantID   INTEGER NOT NULL REFERENCES Restaurants(RestaurantID),
    PartnerID      INTEGER REFERENCES DeliveryPartners(PartnerID),  -- NULL if cancelled before pickup
    OrderedAt      TEXT NOT NULL,               -- 'YYYY-MM-DD HH:MM'
    Status         TEXT NOT NULL,               -- 'Delivered', 'Cancelled'
    DeliveryMins   INTEGER,                     -- NULL unless delivered
    TotalAmount    REAL NOT NULL,
    Rating         INTEGER CHECK (Rating BETWEEN 1 AND 5)  -- customer's rating, may be NULL
);

CREATE TABLE OrderItems (
    OrderItemID  INTEGER PRIMARY KEY,
    OrderID      INTEGER NOT NULL REFERENCES Orders(OrderID),
    ItemID       INTEGER NOT NULL REFERENCES MenuItems(ItemID),
    Quantity     INTEGER NOT NULL
);
