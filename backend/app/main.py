app.add_middleware(CORSMiddleware, allow_origin_regex=r"http://(localhost|127\.0\.0\.1)(:\d+)?",
                   allow_methods=["*"], allow_headers=["*"])

SESSION_RE = re.compile(r"^[A-Za-z0-9_-]{1,64}$")

